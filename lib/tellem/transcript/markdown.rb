# frozen_string_literal: true

require "time"
require_relative "../version"
require_relative "../ids"
require_relative "../ingest/support"
require_relative "tools"

module Tellem
  module Transcript
    module Markdown
      PATTERN = "SpecStory Markdown v2.1.0 pattern"
      HARNESS_LABELS = { "claude" => "Claude Code", "codex" => "Codex" }.freeze
      HEADING_TIME = "%Y-%m-%d %H:%M:%S%z"
      FILE_TIME = "%Y-%m-%d_%H-%M-%S%z"
      SEPARATOR = "\n\n---\n\n"
      JOINER = "\n\n"

      module_function

      def available?
        true
      end

      def foundation_default?
        false
      end

      def render(session:, agent:, exchanges:)
        ordered = order(Array(exchanges))
        started = fetch(session, "started_at")
        start = local(ordered.first&.fetch("ts", nil) || started)
        out = +"<!-- Generated by tellem #{Tellem::VERSION}, #{PATTERN} -->\n\n# #{start}\n\n"
        out << "<!-- #{label(fetch(session, 'harness'))} Session #{fetch(session, 'session_id')} (#{start}) -->\n\n"
        previous = nil
        ordered.each do |exchange|
          body = block(exchange, session, started)
          next if body.nil?

          out << (exchange["role"] == "agent" && previous == "agent" ? JOINER : SEPARATOR) if previous
          out << body
          previous = exchange["role"]
        end
        out << SEPARATOR.rstrip if previous == "user"
        out
      end

      def filename(session_start, title, agent_id: nil)
        stamp = local(session_start, FILE_TIME)
        slug = Ingest::Support.slug(title)
        base = slug.empty? ? stamp : "#{stamp}-#{slug}"
        return base if agent_id.nil? || agent_id.to_s.empty?

        "#{base}--subagent-#{Ids.agent_key(agent_id)}"
      end

      def order(exchanges)
        last = nil
        filled = exchanges.map do |exchange|
          last = exchange["ts"] || last
          [last.to_s, exchange]
        end
        filled.each_with_index.sort_by { |(ts, _exchange), index| [ts, index] }.map { |(_ts, exchange), _index| exchange }
      end

      def block(exchange, session, started)
        body = case exchange["kind"]
               when "text" then text(exchange["text"])
               when "tool" then Tools.block(exchange["tool"], link: link(exchange["tool"], session, started))
               end
        return nil if body.nil? || body.empty?

        "#{heading(exchange)}\n\n#{body}"
      end

      def heading(exchange)
        time = local(shown_time(exchange))
        unless exchange["role"] == "agent"
          return exchange["source"] == "queued" ? "_**User (queued #{time})**_" : "_**User (#{time})**_"
        end

        model = exchange["model"]
        model.is_a?(String) && !model.empty? ? "_**Agent (#{model} #{time})**_" : "_**Agent (#{time})**_"
      end

      def shown_time(exchange)
        tool = exchange["tool"]
        result_at = tool.is_a?(Hash) ? tool["result_at"] : nil
        result_at.is_a?(String) ? result_at : exchange["ts"]
      end

      def text(value)
        return nil unless value.is_a?(String)

        trimmed = value.sub(/\A(?:[ \t]*\n)+/, "").rstrip
        trimmed.empty? ? nil : trimmed
      end

      def link(tool, session, started)
        child = tool["subagent_id"]
        return nil unless child.is_a?(String) && !child.empty?

        "#{filename(started, fetch(session, 'title'), agent_id: child)}.md"
      end

      def local(ts, format = HEADING_TIME)
        return "unknown time" unless ts.is_a?(String) && !ts.empty?

        Time.iso8601(ts).localtime.strftime(format)
      rescue ArgumentError
        "unknown time"
      end

      def label(harness)
        HARNESS_LABELS.fetch(harness.to_s, harness.to_s)
      end

      def fetch(hash, key)
        return nil unless hash.is_a?(Hash)

        hash.key?(key) ? hash[key] : hash[key.to_sym]
      end
    end
  end
end
